<?php

namespace Database\Seeders;

use App\Models\Item;
use App\Models\Location;
use App\Models\WorkArea;
use Illuminate\Database\Seeder;

class BulkItemSeeder extends Seeder
{
    public function run(): void
    {
        $locationIds = Location::pluck('id')->all();
        $workAreaIds = WorkArea::pluck('id')->all();

        $types = [
            'Control Valve',
            'Pressure',
            'Flow',
            'Level',
            'Analyzer',
            'PLC/DCS',
            'Pagging',
            'Burner',
            'Dosometer',
            'Accessories / Sparepart',
            'Bagging & Bagcode',
            'Safety Device',
        ];

        $sapClassifications = [
            'PAGGING',
            'DOSOMETER',
            'Bagging',
            'PLC & DCS',
            'Analyzer',
            'CONTROL VALVE DAN SOV',
            'Other',
        ];

        $units = [
            'Pieces (PCS)',
            'Eaches (EA)',
            'Set (SET)',
            'Unit (UNT)',
            'Meter (M)',
            'Box (BOX)',
        ];

        $now = now();
        $batch = [];
        $total = 2000;

        for ($i = 1; $i <= $total; $i++) {
            $isTool = $i % 4 === 0;
            $stock = rand(0, 50);
            $type = $types[$i % count($types)];
            $mnCode = sprintf('MN-%06d', 100000 + $i);

            $batch[] = [
                'mn_code' => $mnCode,
                'item_name' => ($isTool ? 'Tool ' : 'Sparepart ') . $type . ' #' . $i,
                'sap_description' => 'SAP DESC ' . strtoupper($type) . ' ITEM ' . $i,
                'item_category' => $isTool ? 'tool' : 'consumable_part',
                'type' => $type,
                'unit' => $units[$i % count($units)],
                'no_po' => $i % 3 === 0 ? 'PO-2026-' . str_pad((string) $i, 4, '0', STR_PAD_LEFT) : null,
                'po_numbers' => null,
                'sap_classification' => $sapClassifications[$i % count($sapClassifications)],
                'sap_status' => 'ACTIVE',
                'reorder_point' => rand(2, 10),
                'min_lot_size' => rand(1, 5),
                'system_stock' => $stock,
                'actual_stock' => $stock,
                'last_stock_opname_at' => $now,
                'location_id' => !empty($locationIds) ? $locationIds[$i % count($locationIds)] : null,
                'owner_work_area_id' => !empty($workAreaIds) ? $workAreaIds[$i % count($workAreaIds)] : null,
                'notes' => 'Generated by BulkItemSeeder #' . $i,
                'created_at' => $now,
                'updated_at' => $now,
            ];

            if (count($batch) === 500) {
                Item::insert($batch);
                $batch = [];
            }
        }

        if (!empty($batch)) {
            Item::insert($batch);
        }
    }
}
